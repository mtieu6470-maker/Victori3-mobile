"""Portraits of the historical persons linked by link_people.py (Wikidata P18 -> Wikimedia Commons).

Only 'strong' and 'weak' matches are used; only licences in the allow-list are shipped; files listed in
historical_data/assets/review.json -> reject (e.g. a tomb, a seal or a modern statue used as a person's main
image) are dropped with the reviewer's reason. Output: historical_data/assets/portrait_assets.json and
public/content/portraits/*.webp

    python3 tools/etl/fetch_portraits.py
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from assets import ROOT, commons_info, licence, allowed, store
from wiki import RateLimited
import urllib.error

people = json.load(open(os.path.join(ROOT, 'historical_data/identity/people_links.json'), encoding='utf-8'))['people']
review_path = os.path.join(ROOT, 'historical_data/assets/review.json')
review = json.load(open(review_path, encoding='utf-8')) if os.path.exists(review_path) else {'reject': {}}

todo = {k: p for k, p in people.items() if p.get('match') in ('strong', 'weak') and p.get('image')}
info = commons_info(sorted({p['image'] for p in todo.values()}), 400)
assets, rejected, deferred = [], [], []
done_files = {}
for k, p in sorted(todo.items()):
    f = p['image']
    if f in review['reject']:
        rejected.append({'person': k, 'file': f, 'reason': 'review: ' + review['reject'][f]}); continue
    ii = info.get(f)
    if not ii:
        rejected.append({'person': k, 'file': f, 'reason': 'file missing on Commons'}); continue
    lic = licence(ii)
    if not allowed(lic):
        rejected.append({'person': k, 'file': f, 'reason': 'licence not allowed: ' + lic['short']}); continue
    safe = re.sub(r'[^A-Za-z0-9_]+', '_', k)
    try:
        shipped = done_files.get(f) or store(ii, f'portraits/{safe}.webp', 360, 460, flatten=(20, 28, 33, 255))
    except (RateLimited, urllib.error.HTTPError):
        deferred.append({'person': k, 'file': f, 'reason': 'download rate-limited by Wikimedia; re-run to fetch'}); continue
    done_files[f] = shipped
    assets.append({
        'id': 'portrait.' + k, 'type': 'portrait', 'entity': p['entity'], 'character': k,
        'name': 'Chân dung — ' + (p.get('label_vi') or p.get('label_en') or p['name']),
        'description': lic['description'] or ii['canonical'], 'date': lic['date'] or None,
        'period': {'from': None, 'to': None}, 'quality': 'supported' if p['match'] == 'strong' else 'uncertain',
        'source': {'repository': 'Wikimedia Commons', 'file': ii['canonical'], 'page': ii['descriptionurl'], 'statement': f"wikidata:{p['qid']}#P18"},
        'license': {'short': lic['short'], 'url': lic['url'], 'attribution_required': lic['attribution_required']},
        'author': lic['author'], 'credit': lic['credit'], 'restrictions': lic['restrictions'] or None,
        'original': {'width': ii['width'], 'height': ii['height'], 'mime': ii['mime']},
        **shipped, 'fallback': 'monogram',
    })
os.makedirs(os.path.join(ROOT, 'historical_data/assets'), exist_ok=True)
json.dump({'description': 'Portraits of linked historical persons (generated by tools/etl/fetch_portraits.py).', 'assets': assets, 'rejected': rejected, 'deferred': deferred},
          open(os.path.join(ROOT, 'historical_data/assets/portrait_assets.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('portraits', len(assets), 'rejected', len(rejected), 'deferred', len(deferred), 'bytes', sum(a['bytes'] for a in assets))
