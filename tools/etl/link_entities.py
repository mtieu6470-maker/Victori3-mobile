"""Link each political entity to its Wikidata item and record verification evidence.

Input : historical_data/identity/wiki_titles.json (hand-chosen article per entity, see its description)
Output: historical_data/identity/wikidata_links.json

For every entity: canonical article, QID, instance-of labels, inception / dissolution years, Vietnamese article,
official / native names (with language), and a check that the item's lifetime covers 1836 (or that it is a
future state, a people, a region or a period, for which the check does not apply). Nothing is accepted silently:
'check' is 'ok', 'not_applicable', or a reason, and the review notes are kept in the output.

    python3 tools/etl/link_entities.py
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from wiki import resolve_titles, entities, claim_values, year_of

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
titles = json.load(open(os.path.join(ROOT, 'historical_data/identity/wiki_titles.json'), encoding='utf-8'))['titles']
db = json.load(open(os.path.join(ROOT, 'src/generated/db.json'), encoding='utf-8'))  # run `npm run data` first
ids = [e['id'] for e in db['entities']]
START = 1836

cands = []
for k, v in titles.items():
    if 'qid' not in v:
        cands += [v['t']] + v.get('alt', [])
res = resolve_titles(cands)

chosen = {}
for k, v in titles.items():
    if 'qid' in v:
        chosen[k] = (v['t'], {'title': None, 'qid': v['qid'], 'missing': False})
        continue
    for t in [v['t']] + v.get('alt', []):
        r = res[t]
        if not r['missing'] and r['qid']:
            chosen[k] = (t, r)
            break

ents = entities([r['qid'] for _, r in chosen.values()])
p31 = set()
for e in ents.values():
    for val, _, _ in claim_values(e, 'P31'):
        p31.add(val['id'])
lab = entities(sorted(p31), props='labels', languages='en')
label = {q: e.get('labels', {}).get('en', {}).get('value', q) for q, e in lab.items()}

out = {}
for eid in ids:
    t = titles.get(eid)
    if not t:
        out[eid] = {'linked': False, 'reason': 'no single article describes this aggregate / multi-polity group'}
        continue
    if eid not in chosen:
        out[eid] = {'linked': False, 'reason': 'article not found: ' + ' | '.join([t['t']] + t.get('alt', []))}
        continue
    asked, r = chosen[eid]
    e = ents[r['qid']]
    inc = [year_of(v) for v, _, _ in claim_values(e, 'P571')]
    dis = [year_of(v) for v, _, _ in claim_values(e, 'P576')]
    inc = min((y for y, _ in filter(None, inc)), default=None)
    dis = max((y for y, _ in filter(None, dis)), default=None)
    kind = t['kind']
    if any('disambiguation' in label.get(v['id'], '') for v, _, _ in claim_values(e, 'P31')):
        check = 'article is a disambiguation page'
    elif kind in ('people', 'region', 'period', 'future', 'dynasty'):
        check = 'not_applicable'
    elif inc is not None and inc > START:
        check = f'inception {inc} after {START}'
    elif dis is not None and dis < START:
        check = f'dissolved {dis} before {START}'
    else:
        check = 'ok'
    names = []
    for v, q, rank in claim_values(e, 'P1448') + claim_values(e, 'P1705'):
        if isinstance(v, dict) and 'text' in v:
            st = [year_of(x) for x in q.get('P580', [])]
            en = [year_of(x) for x in q.get('P582', [])]
            names.append({'text': v['text'], 'lang': v.get('language'), 'from': st[0][0] if st and st[0] else None, 'to': en[0][0] if en and en[0] else None, 'rank': rank})
    seen = set(); uniq = []
    for n in names:
        if (n['text'], n['lang']) not in seen:
            seen.add((n['text'], n['lang'])); uniq.append(n)
    out[eid] = {
        'linked': True, 'kind': kind, 'article': r['title'], 'asked': asked, 'qid': r['qid'],
        'label_en': e.get('labels', {}).get('en', {}).get('value'), 'label_vi': e.get('labels', {}).get('vi', {}).get('value'),
        'description_en': e.get('descriptions', {}).get('en', {}).get('value'),
        'viwiki': e.get('sitelinks', {}).get('viwiki', {}).get('title'),
        'instance_of': [label.get(v['id'], v['id']) for v, _, _ in claim_values(e, 'P31')][:6],
        'inception': inc, 'dissolved': dis, 'check': check, 'names': uniq,
        'desc_article': t.get('desc'),
    }

linked = sum(1 for v in out.values() if v['linked'])
bad = {k: v['check'] for k, v in out.items() if v.get('linked') and v['check'] not in ('ok', 'not_applicable')}
doc = {
    'description': 'Wikidata link per political entity with verification evidence (generated by tools/etl/link_entities.py from historical_data/identity/wiki_titles.json). check: ok = item lifetime covers 1836; not_applicable = the article is a people / region / period / dynasty / future state; any other text = mismatch to review. Wikidata content is CC0.',
    'source': {'id': 'wikidata', 'license': 'CC0-1.0', 'url': 'https://www.wikidata.org/'},
    'counts': {'entities': len(ids), 'linked': linked, 'mismatch': len(bad)},
    'links': out,
}
json.dump(doc, open(os.path.join(ROOT, 'historical_data/identity/wikidata_links.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('linked', linked, '/', len(ids))
for k, v in out.items():
    if not v['linked']:
        print('UNLINKED', k, v['reason'])
for k, c in bad.items():
    print('CHECK', k, out[k]['article'], c)
