"""Descriptive text for entities and persons: the lead section of the linked Wikipedia article, in Vietnamese
when the Vietnamese article has a usable lead (>= 250 characters), always with the English lead as well.

Wikipedia text is licensed CC BY-SA 4.0: every text keeps article title, URL, revision id and licence, and the
game shows that attribution next to the text. Leads are cut at a sentence boundary (<= ~1400 characters) and
marked 'truncated'. No text is written or paraphrased here.

Output: historical_data/identity/texts.json        python3 tools/etl/fetch_texts.py
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from wiki import api, chunks, resolve_titles, entities

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
links = json.load(open(os.path.join(ROOT, 'historical_data/identity/wikidata_links.json'), encoding='utf-8'))['links']
people = json.load(open(os.path.join(ROOT, 'historical_data/identity/people_links.json'), encoding='utf-8'))['people']
LIMIT = 1400


def leads(titles, lang):
    out = {}
    for part in chunks(sorted(set(titles)), 20):
        d = api(f'{lang}.wikipedia.org', action='query', prop='extracts|info|revisions', exintro=1, explaintext=1, exlimit=20,
                inprop='url', rvprop='ids|timestamp', titles='|'.join(part), redirects=1)
        q = d['query']
        back = {}
        for n in q.get('normalized', []) + q.get('redirects', []):
            back[n['to']] = back.get(n['from'], n['from'])
        for p in q['pages']:
            if p.get('missing') or not p.get('extract'):
                continue
            src = back.get(p['title'], p['title'])
            for t in part:
                if t == src or t == p['title']:
                    rev = (p.get('revisions') or [{}])[0]
                    out[t] = {'title': p['title'], 'url': p.get('fullurl'), 'revid': rev.get('revid'), 'retrieved': (rev.get('timestamp') or '')[:10], 'raw': p['extract']}
    return out


def cut(text):
    text = re.sub(r'\n{2,}', '\n', text).strip()
    text = re.sub(r'\s*\([^()]*(?:listen|pronunciation|IPA|/)[^()]*\)', '', text)  # pronunciation clutter
    if len(text) <= LIMIT:
        return text, False
    s = text[:LIMIT]
    m = max(s.rfind('. '), s.rfind('.\n'), s.rfind('。'))
    return (s[:m + 1] if m > 400 else s.rstrip() + '…'), True


def pack(rec, lang):
    t, tr = cut(rec['raw'])
    return {'lang': lang, 'text': t, 'truncated': tr, 'article': rec['title'], 'url': rec['url'], 'revid': rec['revid'], 'retrieved': rec['retrieved'],
            'license': 'CC BY-SA 4.0', 'license_url': 'https://creativecommons.org/licenses/by-sa/4.0/', 'author': 'Wikipedia contributors'}


# entity -> (en title, vi title)
ent_titles = {}
over = [l['desc_article'] for l in links.values() if l.get('linked') and l.get('desc_article')]
over_res = resolve_titles(over)
over_ent = entities([r['qid'] for r in over_res.values() if r['qid']], props='sitelinks')
for eid, l in links.items():
    if not l.get('linked') or not l.get('article'):
        continue
    if l.get('desc_article'):
        r = over_res[l['desc_article']]
        vi = over_ent.get(r['qid'], {}).get('sitelinks', {}).get('viwiki', {}).get('title') if r['qid'] else None
        ent_titles[eid] = (r['title'], vi, True)
    else:
        ent_titles[eid] = (l['article'], l.get('viwiki'), False)
per_titles = {k: (p.get('enwiki'), p.get('viwiki')) for k, p in people.items() if p.get('match') in ('strong', 'weak')}

en = leads([t for t, _, _ in ent_titles.values()] + [t for t, _ in per_titles.values() if t], 'en')
vi = leads([v for _, v, _ in ent_titles.values() if v] + [v for _, v in per_titles.values() if v], 'vi')


def texts(t_en, t_vi):
    out = []
    if t_vi and t_vi in vi and len(vi[t_vi]['raw']) >= 250:
        out.append(pack(vi[t_vi], 'vi'))
    if t_en and t_en in en:
        out.append(pack(en[t_en], 'en'))
    return out

doc = {'description': 'Lead sections of the linked Wikipedia articles (generated by tools/etl/fetch_texts.py). Text is CC BY-SA 4.0 by Wikipedia contributors; each item carries its article, URL and revision. desc_override = the article describes the period rather than the polity item itself.',
       'entities': {}, 'people': {}}
for eid, (te, tv, ov) in ent_titles.items():
    t = texts(te, tv)
    if t:
        doc['entities'][eid] = {'desc_override': ov, 'texts': t}
for k, (te, tv) in per_titles.items():
    t = texts(te, tv)
    if t:
        doc['people'][k] = {'texts': t}
json.dump(doc, open(os.path.join(ROOT, 'historical_data/identity/texts.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('entities', len(doc['entities']), 'with vi', sum(1 for v in doc['entities'].values() if v['texts'][0]['lang'] == 'vi'),
      'people', len(doc['people']), 'with vi', sum(1 for v in doc['people'].values() if v['texts'][0]['lang'] == 'vi'))
