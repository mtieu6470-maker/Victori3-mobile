const lines = readFileSync(new URL('../../docs/research/data/CG37_DECOLONISATION_1945_1990.csv', import.meta.url), 'utf8').trim().split('\n').slice(1);
const parse = (l: string) => { const out: string[] = []; let cur = '', q = false; for (const ch of l) { if (ch === '"') q = !q; else if (ch === ',' && !q) { out.push(cur); cur = ''; } else cur += ch; } out.push(cur); return out; };
loadNodeData();
const st = createGame({ mode: 'historical', seed: 1, player: null });
const shares = regionCountryShares(st);
const records = [];
for (const l of lines) {
  // The CSV header lists 6 columns, but each row carries 7 fields: ISO3, name, power, date, mode, predecessor, source, notes.
  const [iso, name, power, date, mode, predecessor, source] = parse(l);
  const y = Number(date.slice(0, 4));
  if (!(y >= 1836 && y <= 2026)) continue;
  const regions = [...shares].filter(([, m]) => (m.get(iso) ?? 0) >= 0.5).map(([id]) => id).sort();
  records.push({ id: `indep_${iso.toLowerCase()}`, iso, name, name_vi: VI[iso] ?? name, power, date, mode, predecessor, source, regions });
}
writeFileSync(new URL('../../historical_data/decolonisation/independence.json', import.meta.url), JSON.stringify({
  description: 'DECOL-01 Historical Mode independence events, generated by tools/data/build-decolonisation.ts from the CG-37 research register (ChatGPT, 2026-11-23; sources per record). regions = engine regions lying >= 50% in the modern country. Records before 1836 (Latin America) are excluded.',
  records,
}, null, 1) + '\n');
